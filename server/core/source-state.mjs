import path from "node:path";
import { git, gitRaw } from "./git.mjs";
import {
  bytesOrNull,
  jsonOrNull,
  safeFile,
  digest,
  objectHash,
} from "./files.mjs";
import {
  fingerprintDirectory,
  packPluginDirectory,
  BUNDLE_MARKER,
} from "./bundle.mjs";

// Install-time build steps overwrite committed placeholder files with
// generated bundles (better-paseo writes a ~715KB client chunk into
// server/tasks-chunk.ts on every install/update), so the checkout is dirty
// by design. Such files announce themselves through a generated header on
// their first line and are not local source edits. A plugin may declare
// "installBuildFiles" in its paseo-plugin.json to scope the recognition to
// an explicit file list; without the declaration any modified tracked file
// carrying the marker qualifies.
const INSTALL_GENERATED_MARKER = /generated by .*do not edit or commit/i;

async function isInstallGenerated(top, name, scope) {
  if (scope !== null && !scope.has(name)) return false;
  try {
    const raw = await bytesOrNull(await safeFile(top, name));
    if (raw === null) return false;
    const firstLine = raw.subarray(0, 256).toString("utf8").split("\n")[0];
    return INSTALL_GENERATED_MARKER.test(firstLine);
  } catch {
    return false;
  }
}

async function installBuildScope(row, top) {
  let files;
  try {
    const manifest = await jsonOrNull(
      await safeFile(row.path, "paseo-plugin.json"),
    );
    files = manifest?.installBuildFiles;
  } catch {
    return null;
  }
  if (!Array.isArray(files)) return null;
  // Manifest paths are plugin-relative; git status reports names relative
  // to the toplevel, so a plugin in a repository subdirectory must be
  // normalized the same way as the patch allowance below. safeFile resolves
  // the row root through realpath so macOS /var checkouts match the
  // toplevel git reports (/private/var). Unsafe entries never match a
  // status name and are dropped.
  const names = [];
  for (const f of files) {
    if (typeof f !== "string") continue;
    try {
      names.push(
        path
          .relative(top, await safeFile(row.path, f))
          .split(path.sep)
          .join("/"),
      );
    } catch {
      // skip entries with unsafe relative paths
    }
  }
  return new Set(names);
}

export async function sourceState(row, profile) {
  if (row.installation?.identity.kind === "directory" && row.path) {
    const metaFile = path.join(row.path, BUNDLE_MARKER);
    const raw = await bytesOrNull(metaFile);
    if (!raw) return null;
    try {
      const meta = JSON.parse(raw.toString("utf8"));
      if (!meta.source?.startsWith("bundle:") || !meta.revision) return null;
      const currentFiles = await fingerprintDirectory(row.path);
      const changed = [];
      if (meta.files && typeof meta.files === "object") {
        const expectedFiles = meta.files;
        const allPaths = new Set([
          ...Object.keys(currentFiles),
          ...Object.keys(expectedFiles),
        ]);
        for (const p of allPaths) {
          if (currentFiles[p] !== expectedFiles[p]) {
            changed.push(p);
          }
        }
      } else {
        // Fallback for bundles without per-file fingerprints
        const packed = await packPluginDirectory(row.path);
        if (packed.sha256 !== meta.revision) {
          changed.push("*");
        }
      }
      changed.sort();
      const clean = changed.length === 0;
      return {
        clean,
        head: meta.revision,
        statusHash: objectHash(changed),
        changed,
      };
    } catch {
      return null;
    }
  }
  if (row.installation?.identity.kind !== "git") return null;
  const head = await git(row.path, "rev-parse", "HEAD");
  const status = await gitRaw(
    row.path,
    "status",
    "--porcelain=v1",
    "--untracked-files=all",
    "-z",
  );
  const top = await git(row.path, "rev-parse", "--show-toplevel");
  const allowed = new Map();
  for (const b of profile.patches.filter((b) => b.plugin === row.id))
    for (const f of b.data.files) {
      const name = path
        .relative(top, path.join(row.path, ...f.path.split("/")))
        .split(path.sep)
        .join("/");
      const raw = await bytesOrNull(await safeFile(row.path, f.path));
      if (raw !== null && digest(raw) === f.afterSha256)
        allowed.set(name, true);
    }
  const scope = await installBuildScope(row, top);
  const changed = [];
  const parts = status.split("\0");
  for (let i = 0; i < parts.length; i++) {
    const entry = parts[i];
    if (!entry) continue;
    const mode = entry.slice(0, 2),
      name = entry.slice(3);
    if (mode !== " M" || !allowed.has(name)) {
      if (mode === " M" && (await isInstallGenerated(top, name, scope)))
        continue;
      changed.push(name);
    }
    if (/[RC]/.test(mode)) {
      i++;
      if (parts[i]) changed.push(parts[i]);
    }
  }
  const clean =
    head === row.installation.currentRevision && changed.length === 0;
  return { clean, head, statusHash: objectHash(status), changed };
}
